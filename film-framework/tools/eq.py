#!/usr/bin/env python3
"""LaTeX 公式 → mathkit.Eq 的预生成管线。

用 matplotlib 的 mathtext（无需装 LaTeX）把公式渲染成字形轮廓，
展平成折线，直接吐出一个 Go 源文件——公式成为编译期常量，
运行时零依赖、逐像素确定。

    /tmp/mathkit-venv/bin/python tools/eq.py <out.go> <package> \\
        name1="tex1" name2="tex2" ...

生成侧约定（和 mathkit.Eq 对齐）：
  - 字号 100 时的像素坐标；
  - 原点在公式的左基线，y 向下（TextPath 是 y 向上，这里翻过来）；
  - W/H 是公式的包围盒宽高。
"""
import sys

from matplotlib.font_manager import FontProperties
from matplotlib.textpath import TextPath

SIZE = 100  # 与 mathkit.eqScaleRef 对齐


def eq_lines(tex):
    """一条 TeX 公式 → (polys, width, height)。

    polys 是 [[x, y, x, y, ...], ...] 的列表，y 已翻成向下，
    基线在 y=0，字形主体在 y<0。
    """
    tp = TextPath((0, 0), tex, prop=FontProperties(size=SIZE), usetex=False)
    polys = tp.to_polygons()
    lines = []
    for arr in polys:
        pts = []
        for x, y in arr:
            pts += [round(float(x), 2), round(float(-y), 2)]
        if len(pts) >= 6:
            lines.append(pts)
    if not lines:
        raise SystemExit(f"no outlines for {tex!r}")
    xs = [lines[i][j] for i in range(len(lines)) for j in range(0, len(lines[i]), 2)]
    ys = [lines[i][j] for i in range(len(lines)) for j in range(1, len(lines[i]), 2)]
    w = max(xs) - min(xs)
    h = max(ys) - min(ys)  # 全为负，高度是它的绝对值
    return lines, round(w, 2), round(-max(ys), 2), round(-min(ys), 2)


def go_float(v):
    """Go 字面量：整数补 .0，避免和类型较劲。"""
    s = f"{v:g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s


def emit(out, package, names):
    w = max(len(n) for n, _ in names)
    with open(out, "w") as f:
        f.write("// Code generated by tools/eq.py; DO NOT EDIT.\n\n")
        f.write(f"package {package}\n\n")
        f.write('import "nsgofilm/mathkit"\n\n')
        for name, tex in names:
            lines, width, top, bottom = eq_lines(tex)
            f.write(f"// {tex}\n")
            f.write(f"var Eq{name.ljust(w)} = mathkit.Eq{{W: {go_float(width)}, H: {go_float(top + bottom)}, Lines: []mathkit.Poly{{\n")
            for pts in lines:
                body = ", ".join(go_float(v) for v in pts)
                f.write(f"    {{Pts: []float32{{{body}}}, Closed: true}},\n")
            f.write("}}\n\n")
        f.write(f"// 基线参考：y 范围 [{', '.join(str(eq_lines(t)[3]) for _, t in names)}]（字号 100）。\n")


def main():
    args = sys.argv[1:]
    if len(args) < 3:
        print(__doc__)
        sys.exit(2)
    out, package = args[0], args[1]
    pairs = []
    for a in args[2:]:
        name, sep, tex = a.partition("=")
        if not name or not sep or not tex:
            print(__doc__)
            sys.exit(2)
        pairs.append((name, tex))
    emit(out, package, pairs)
    print(f"wrote {out}: {', '.join(n for n, _ in pairs)}")


if __name__ == "__main__":
    main()
